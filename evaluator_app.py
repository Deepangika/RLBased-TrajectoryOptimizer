import os
import gradio as gt
import time
from google import genai
from google.genai import types
from PIL import Image

# Initialize the client. Ensure your GEMINI_API_KEY environment variable is set.
# Alternatively, replace this block with your local PyTorch model inference code.
try:
    client = genai.Client()
except Exception:
    client = None

def evaluate_trajectory_affect(gif_path):
    if not gif_path:
        return "Please upload a trajectory GIF first.", ""
        
    if client is None:
        return "Backend Error: Gemini API client not initialized.", "Unknown"

    try:
        # 1. Upload the GIF using the File API instead of passing raw bytes
        # This forces the backend to unpack it as a sequence of frames
        print(f"Uploading {gif_path} to Gemini File API...")
        uploaded_file = client.files.upload(file=gif_path)
        
        # 2. Wait briefly for the API to process the video frames
        # (Crucial for video/GIF files so the model can read the temporal data)
        while uploaded_file.state.name == "PROCESSING":
            print("Processing trajectory frames...")
            time.sleep(2)
            uploaded_file = client.files.get(name=uploaded_file.name)
            
        if uploaded_file.state.name == "FAILED":
            return "File processing failed on the server side.", "Error"

        # Define prompts
        system_instruction = (
            "You are an expert movement evaluator specializing in Laban Movement Analysis (LMA) "
            "and Affective Computing. Your task is to look at a trajectory video/GIF of an agent "
            "and evaluate its emotional/affective state based on its kinematic properties."
        )
        
        prompt = (
            "Analyze this trajectory motion file. Follow these steps:\n"
            "1. KINEMATIC OBSERVATION: Describe the velocity, acceleration, jerk, and path curvature.\n"
            "2. LABAN EFFORT ANALYSIS: Evaluate the motion along the 4 LMA Effort dimensions:\n"
            "   - Space (Direct vs. Indirect)\n"
            "   - Weight (Strong vs. Light)\n"
            "   - Time (Sudden vs. Sustained)\n"
            "   - Flow (Bound vs. Free)\n"
            "3. AFFECTIVE PREDICTION: Conclude with the primary affective state/emotion being depicted "
            "and give your confidence score (0-100%)."
        )

        # 3. Request evaluation passing the processed file handle
        response = client.models.generate_content(
            model='gemini-2.5-flash',
            contents=[uploaded_file, prompt],
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.2,
            )
        )
        
        # Clean up the file from the cloud storage after processing
        try:
            client.files.delete(name=uploaded_file.name)
        except Exception:
            pass # Fail silently if deletion fails

        # Post-processing to extract clean class name
        full_analysis = response.text
        predicted_label = "Analyzed (See Details)"
        
        for line in full_analysis.split('\n'):
            if "AFFECTIVE PREDICTION:" in line.upper() or "EMOTION:" in line.upper():
                predicted_label = line.split(":")[-1].strip()
                break

        return full_analysis, predicted_label

    except Exception as e:
        return f"An error occurred during evaluation: {str(e)}", "Error"

# --- Gradio UI Layout ---
with gt.Blocks(theme=gt.themes.Soft()) as demo:
    gt.Markdown(
        """
        # 🏃‍♂️ Laban-inspired RL Trajectory Affect Evaluator
        Upload a `.gif` of your variant trajectory generated by your Reinforcement Learning policy. 
        The evaluator will dissect the motion dynamics using Laban Movement Analysis (LMA) frameworks to deduce the expressed affect.
        """
    )
    
    with gt.Row():
        with gt.Column(scale=1):
            input_gif = gt.Image(
                label="Upload Variant Motion GIF", 
                type="filepath", 
                sources=["upload"]
            )
            evaluate_btn = gt.Button("Evaluate Affective State", variant="primary")
            
        with gt.Column(scale=1):
            predicted_affect = gt.Label(label="Predicted Affective State")
            detailed_report = gt.Textbox(
                label="Detailed Kinematic & Laban Analysis Report", 
                interactive=False, 
                lines=12
            )
            
    # Connect trigger
    evaluate_btn.click(
        fn=evaluate_trajectory_affect,
        inputs=[input_gif],
        outputs=[detailed_report, predicted_affect]
    )

if __name__ == "__main__":
    # Launch locally. To share a public link, change share=True
    demo.launch(share=False)